const speechRaw = (await fs.readFile('research/speech-full.json', 'utf8')).replace(/^\uFEFF/, '');
const speech = JSON.parse(speechRaw);

const section = (i) =>
  i === 0
    ? '培训学习汇报'
    : i < 3
      ? '01 / 基础概念与总流程'
      : i < 10
        ? '02 / 蛋白质前处理'
        : i < 20
          ? '03 / 样品上机与仪器工作'
          : i < 27
            ? '04 / 结果解读与微生态应用'
            : '总结与回顾';

const pages = slides.map((s, i) => {
  s.section = section(i);
  s.outlineNotes = (outlineRows[i] || '').split('|')[5]?.trim() || '';
  const paras = (speech[i] || []).join('\n\n');
  return `<section class="deck-page ${s.layout}" data-slide="${i + 1}"><header><div class="section-label">${s.section}</div><h1>${s.title}</h1><p>${s.sub}</p></header><main>${s.body}</main><footer><span>${s.source}</span><b>${String(i + 1).padStart(2, '0')} / 28</b></footer></section>\n\n<!--\n逐页演讲稿：\n${paras}\n\n原讲者备注：${s.notes}\n大纲检查点：${s.outlineNotes}\n培训来源索引：research/source-index.json；页码均为PDF物理页。\n-->`;
});

const front = `---\ntheme: default\ntitle: timsTOF 蛋白质组学实验入门汇报\ninfo: 28页入门重构版｜蛋白质前处理、样品上机、质谱原理与结果解读应用\ncanvasWidth: 1280\naspectRatio: 16/9\nrouterMode: hash\nfavicon: /favicon.svg\nfonts:\n  sans: Microsoft YaHei\n  provider: none\ncolorSchema: light\ndrawings:\n  enabled: false\n---\n\n`;

await fs.writeFile('web/slides.md', front + pages.join('\n\n---\n\n'));
await fs.writeFile('research/full-web-content.json', JSON.stringify(slides, null, 2));
await fs.writeFile(
  'research/speaker-notes.md',
  '# timsTOF 28页讲者备注与逐页演讲稿（入门重构版）\n\n' +
    slides
      .map(
        (s, i) =>
          `## ${String(i + 1).padStart(2, '0')} ${s.title}\n\n${(speech[i] || []).join('\n\n')}\n\n原讲者备注：${s.notes}\n\n来源：${s.source}\n\n大纲检查点：${s.outlineNotes}`
      )
      .join('\n\n')
);
console.log('Generated 28-slide WebPPT and speaker notes. No PPTX exported.');
